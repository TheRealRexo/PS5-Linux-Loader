#!/usr/bin/env python3
"""gen_manifest.py - convert tools/images.json into a C header the payload embeds.

Reads tools/images.json and writes include/images_manifest.h containing a
static array of { name, img_url } entries plus a "latest" entry. The payload
WebUI renders these so the user can download the official OS image straight
from the GitHub release (in-payload HTTP download).

Each image entry is either:
  - single-part:  "filename": "ps5-arch-os"  -> <base>/ps5-arch-os.img.xz
  - multi-part:   "filename": "ps5-bazzite-os", "parts": 2
                   -> <base>/ps5-bazzite-os.img.xz, .img.xz.part2, ...
  where <base> is "https://github.com/<repo>/releases/download".
  The filename is the stem; .img.xz is appended by part_url().

The .json itself is committed to the repo; this header is a build-time render
of it so the payload works offline.
"""
import json
import sys
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, os.pardir))
JSON_PATH = os.path.join(REPO_ROOT, "tools", "images.json")
OUT_PATH = os.path.join(REPO_ROOT, "include", "images_manifest.h")

ESCAPE = str.maketrans({
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
})


def c_str(s):
    return '"' + s.translate(ESCAPE) + '"'


def part_url(base, filename, part):
    """Generate URL for part `part` of `filename`.

    - filename can be "ps5-arch-os", "ps5-arch-os.img", or "ps5-arch-os.img.xz"
    - part 1 returns <base>/<filename>.img.xz
    - parts 2..N return <base>/<filename>.img.xz.partN  (with .img.xz stem preserved)
    """
    # Normalize: strip any existing .img or .img.xz suffix
    stem = filename
    if stem.endswith(".img.xz"):
        stem = stem[:-7]
    elif stem.endswith(".img"):
        stem = stem[:-4]
    if part <= 1:
        return "%s/%s.img.xz" % (base, stem)
    return "%s/%s.img.xz.part%d" % (base, stem, part)


def main():
    json_path = sys.argv[1] if len(sys.argv) > 1 else JSON_PATH
    out_path = sys.argv[2] if len(sys.argv) > 2 else OUT_PATH
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    base = (data.get("base_url") or "").rstrip("/")
    if not base:
        base = "https://github.com/%s/releases/latest" % data.get("repo", "")

    images = data.get("images", [])
    if isinstance(images, dict):
        items = sorted(images.items(), key=lambda kv: kv[0])
        items = [(k, v) for k, v in items]
    else:
        items = [(e.get("id") or e.get("name"), e) for e in images]
        items.sort(key=lambda kv: kv[0])

    lines = [
        "/* Generated by tools/gen_manifest.py from tools/images.json. Do not edit by hand. */",
        "#ifndef IMAGES_MANIFEST_H",
        "#define IMAGES_MANIFEST_H",
        "",
        "#include <stddef.h>",
        "",
        "struct image_entry {",
        "    const char *name;   /* distro display name, e.g. Arch Linux */",
        "    const char *img_url; /* first part of the .img download URL (GitHub release) */",
        "    int parts;          /* number of .partN files to concatenate, 1 = single */",
        "};",
        "",
        "static const struct image_entry images_manifest[] = {",
    ]

    for key, info in items:
        name = info.get("name", key)
        filename = info.get("filename", "")
        parts = int(info.get("parts", 1) or 1)
        if parts < 1:
            parts = 1
        url = part_url(base, filename, 1)
        lines.append("    { %s, %s, %d }," % (c_str(name), c_str(url), parts))

    lines += [
        "};",
        "",
        "static const size_t images_manifest_count =",
        "    sizeof(images_manifest) / sizeof(images_manifest[0]);",
        "",
        "#endif /* IMAGES_MANIFEST_H */",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d images, base=%s)" % (out_path, len(items), base))


if __name__ == "__main__":
    main()