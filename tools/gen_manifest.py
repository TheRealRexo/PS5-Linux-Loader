#!/usr/bin/env python3
"""gen_manifest.py - convert tools/images.json into a C header the payload can embed.

Reads tools/images.json and writes include/images_manifest.h containing a
static array of { name, img_url } entries. The payload WebUI renders these so
the user can see which official .img to download (from R2) and transfer to the
PS5 (USB or M.2). The .json itself is committed to the repo; this header is a
build-time render of it so the payload works offline.
"""
import json
import sys
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, os.pardir))
JSON_PATH = os.path.join(REPO_ROOT, "tools", "images.json")
OUT_PATH = os.path.join(REPO_ROOT, "include", "images_manifest.h")

ESCAPE = str.maketrans({
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
})


def c_str(s):
    return '"' + s.translate(ESCAPE) + '"'


def main():
    json_path = sys.argv[1] if len(sys.argv) > 1 else JSON_PATH
    out_path = sys.argv[2] if len(sys.argv) > 2 else OUT_PATH
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    images = data.get("images", [])
    # Accept either a list of {id,name,url,...} or a dict keyed by id.
    if isinstance(images, dict):
        items = sorted(images.items(), key=lambda kv: kv[0])
        items = [(k, v) for k, v in items]
    else:
        items = [( (e.get("id") or e.get("name")), e) for e in images]
        items.sort(key=lambda kv: kv[0])
    lines = [
        "/* Generated by tools/gen_manifest.py from tools/images.json. Do not edit by hand. */",
        "#ifndef IMAGES_MANIFEST_H",
        "#define IMAGES_MANIFEST_H",
        "",
        "#include <stddef.h>",
        "",
        "struct image_entry {",
        "    const char *name;   /* distro key, e.g. arch */",
        "    const char *img_url; /* direct .img.xz download URL (R2) */",
        "};",
        "",
        "static const struct image_entry images_manifest[] = {",
    ]
    for name, info in items:
        url = info.get("url", "")
        disp = info.get("name", name)
        lines.append("    { %s, %s }," % (c_str(disp), c_str(url)))
    lines += [
        "};",
        "",
        "static const size_t images_manifest_count =",
        "    sizeof(images_manifest) / sizeof(images_manifest[0]);",
        "",
        "#endif /* IMAGES_MANIFEST_H */",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d images)" % (out_path, len(items)))


if __name__ == "__main__":
    main()
